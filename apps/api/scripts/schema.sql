/* Perfil mestre: fonte da verdade para todos os currículos gerados. */
CREATE TABLE PROFILES (
    ID            VARCHAR(64)   NOT NULL,
    FULL_NAME     VARCHAR(200)  DEFAULT '' NOT NULL,
    TARGET_TITLE  VARCHAR(200)  DEFAULT '' NOT NULL,
    SUMMARY       BLOB SUB_TYPE TEXT,
    EMAIL         VARCHAR(200),
    PHONE         VARCHAR(60),
    LINKEDIN      VARCHAR(300),
    GITHUB        VARCHAR(300),
    PORTFOLIO     VARCHAR(300),
    LOCATION      VARCHAR(200),
    CREATED_AT    TIMESTAMP     NOT NULL,
    UPDATED_AT    TIMESTAMP     NOT NULL,
    CONSTRAINT PK_PROFILES PRIMARY KEY (ID)
);

CREATE TABLE EDUCATION (
    ID           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PROFILE_ID   VARCHAR(64)  NOT NULL,
    SEQ     SMALLINT     NOT NULL,
    DEGREE       VARCHAR(300) NOT NULL,
    INSTITUTION  VARCHAR(300) NOT NULL,
    START_DATE   VARCHAR(30),
    END_DATE     VARCHAR(30),
    DESCRIPTION  BLOB SUB_TYPE TEXT,
    CONSTRAINT PK_EDUCATION PRIMARY KEY (ID),
    CONSTRAINT FK_EDUCATION_PROFILE FOREIGN KEY (PROFILE_ID)
        REFERENCES PROFILES (ID) ON DELETE CASCADE
);

CREATE TABLE EXPERIENCES (
    ID           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PROFILE_ID   VARCHAR(64)  NOT NULL,
    SEQ     SMALLINT     NOT NULL,
    ROLE_TITLE   VARCHAR(300) NOT NULL,
    COMPANY      VARCHAR(300) NOT NULL,
    START_DATE   VARCHAR(30),
    END_DATE     VARCHAR(30),
    DESCRIPTION  BLOB SUB_TYPE TEXT,
    CONSTRAINT PK_EXPERIENCES PRIMARY KEY (ID),
    CONSTRAINT FK_EXPERIENCES_PROFILE FOREIGN KEY (PROFILE_ID)
        REFERENCES PROFILES (ID) ON DELETE CASCADE
);

CREATE TABLE EXPERIENCE_SKILLS (
    EXPERIENCE_ID  INTEGER      NOT NULL,
    SEQ       SMALLINT     NOT NULL,
    SKILL          VARCHAR(200) NOT NULL,
    CONSTRAINT PK_EXPERIENCE_SKILLS PRIMARY KEY (EXPERIENCE_ID, SEQ),
    CONSTRAINT FK_EXPSKILLS_EXPERIENCE FOREIGN KEY (EXPERIENCE_ID)
        REFERENCES EXPERIENCES (ID) ON DELETE CASCADE
);

CREATE TABLE PROJECTS (
    ID           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PROFILE_ID   VARCHAR(64)  NOT NULL,
    SEQ     SMALLINT     NOT NULL,
    NAME         VARCHAR(300) NOT NULL,
    DESCRIPTION  BLOB SUB_TYPE TEXT,
    URL          VARCHAR(500),
    CONSTRAINT PK_PROJECTS PRIMARY KEY (ID),
    CONSTRAINT FK_PROJECTS_PROFILE FOREIGN KEY (PROFILE_ID)
        REFERENCES PROFILES (ID) ON DELETE CASCADE
);

CREATE TABLE PROJECT_SKILLS (
    PROJECT_ID  INTEGER      NOT NULL,
    SEQ    SMALLINT     NOT NULL,
    SKILL       VARCHAR(200) NOT NULL,
    CONSTRAINT PK_PROJECT_SKILLS PRIMARY KEY (PROJECT_ID, SEQ),
    CONSTRAINT FK_PROJSKILLS_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROJECTS (ID) ON DELETE CASCADE
);

CREATE TABLE SKILL_GROUPS (
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PROFILE_ID  VARCHAR(64)  NOT NULL,
    SEQ    SMALLINT     NOT NULL,
    TITLE       VARCHAR(200) NOT NULL,
    CONSTRAINT PK_SKILL_GROUPS PRIMARY KEY (ID),
    CONSTRAINT FK_SKILLGROUPS_PROFILE FOREIGN KEY (PROFILE_ID)
        REFERENCES PROFILES (ID) ON DELETE CASCADE
);

CREATE TABLE SKILL_GROUP_ITEMS (
    GROUP_ID  INTEGER      NOT NULL,
    SEQ  SMALLINT     NOT NULL,
    SKILL     VARCHAR(200) NOT NULL,
    CONSTRAINT PK_SKILL_GROUP_ITEMS PRIMARY KEY (GROUP_ID, SEQ),
    CONSTRAINT FK_GROUPITEMS_GROUP FOREIGN KEY (GROUP_ID)
        REFERENCES SKILL_GROUPS (ID) ON DELETE CASCADE
);

CREATE TABLE LANGUAGES (
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    PROFILE_ID  VARCHAR(64) NOT NULL,
    SEQ    SMALLINT    NOT NULL,
    NAME        VARCHAR(100) NOT NULL,
    LEVEL_NAME  VARCHAR(100) NOT NULL,
    CONSTRAINT PK_LANGUAGES PRIMARY KEY (ID),
    CONSTRAINT FK_LANGUAGES_PROFILE FOREIGN KEY (PROFILE_ID)
        REFERENCES PROFILES (ID) ON DELETE CASCADE
);

/* Currículos gerados por vaga. As colunas escalares alimentam o histórico
   e os relatórios; CONTENT guarda o documento completo em JSON. */
CREATE TABLE TAILORED_RESUMES (
    ID               VARCHAR(36)   NOT NULL,
    PROFILE_ID       VARCHAR(64)   NOT NULL,
    FILE_NAME        VARCHAR(300)  NOT NULL,
    JOB_TITLE        VARCHAR(300)  NOT NULL,
    COMPANY          VARCHAR(300),
    FOCUS            VARCHAR(20)   NOT NULL,
    SENIORITY        VARCHAR(20)   NOT NULL,
    ATS_BASELINE     SMALLINT      NOT NULL,
    ATS_SCORE        SMALLINT      NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL,
    CONTENT          BLOB SUB_TYPE TEXT NOT NULL,
    CONSTRAINT PK_TAILORED_RESUMES PRIMARY KEY (ID),
    CONSTRAINT FK_RESUMES_PROFILE FOREIGN KEY (PROFILE_ID)
        REFERENCES PROFILES (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RESUMES_SCORE CHECK (ATS_SCORE BETWEEN 0 AND 100)
);

CREATE DESCENDING INDEX IDX_RESUMES_CREATED ON TAILORED_RESUMES (CREATED_AT);
CREATE INDEX IDX_RESUMES_FOCUS ON TAILORED_RESUMES (FOCUS);

/* Relatório: desempenho dos currículos por foco de vaga. */
CREATE VIEW V_RESUME_REPORT AS
SELECT
    FOCUS,
    COUNT(*)                                  AS TOTAL,
    CAST(AVG(ATS_BASELINE * 1.0) AS NUMERIC(5,1)) AS AVG_BASELINE,
    CAST(AVG(ATS_SCORE * 1.0)    AS NUMERIC(5,1)) AS AVG_SCORE,
    MAX(ATS_SCORE)                            AS BEST_SCORE,
    MAX(CREATED_AT)                           AS LAST_GENERATED
FROM TAILORED_RESUMES
GROUP BY FOCUS;
